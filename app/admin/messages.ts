export const ADMIN_MESSAGES: Record<AdminLocale, Record<AdminMessageKey, string>> = { en, ar };

/** The text for `key` in `locale`, with `{name}` placeholders filled in. */
export function adminT(locale: AdminLocale, key: AdminMessageKey, vars: Record<string, string | number> = {}): string {
  const text = ADMIN_MESSAGES[locale][key] ?? en[key];
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}
